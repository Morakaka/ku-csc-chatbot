# ---------------------------------------------------------------------------
# 3) รวม KEYWORD ทั้งหมดเป็น dict เดียว และเรียงลำดับคำยาว -> สั้น
#    เพื่อป้องกันปัญหา "อาคาร 1" ไปจับคู่ผิดกับ "อาคาร 12" (substring ชนกัน)
# ---------------------------------------------------------------------------
_FLAT_KEYWORDS = {}
for _category, _pairs in CATEGORIES.items():
    for _keyword, _answer in _pairs.items():
        _FLAT_KEYWORDS[_keyword] = _answer

# เรียงคำสำคัญจากยาวไปสั้น เพื่อให้เช็คคำที่เจาะจงกว่าก่อนเสมอ
SORTED_KEYWORDS = sorted(_FLAT_KEYWORDS.keys(), key=len, reverse=True)


def find_answer(user_text: str):
    """
    ค้นหาคำตอบจากข้อความผู้ใช้
    - ถ้าพิมพ์ 'เมนู' หรือ 'help' จะได้รายการหมวดหมู่ทั้งหมด
    - ถ้าไม่เจอคำสำคัญใดเลย จะตอบข้อความ fallback พร้อมเบอร์ฉุกเฉิน
    """
    text = user_text.strip()

    if text in ("เมนู", "menu", "help", "ช่วยเหลือ"):
        lines = ["พิมพ์คำถามเกี่ยวกับหมวดต่อไปนี้ได้เลยครับ:"]
        for category, pairs in CATEGORIES.items():
            example_keywords = "、".join(list(pairs.keys())[:3])
            lines.append(f"• {category} (เช่น {example_keywords})")
        lines.append("\nหรือพิมพ์ 'ฉุกเฉิน' เพื่อดูเบอร์ติดต่อกรณีเร่งด่วน")
        return "\n".join(lines)

    if text in ("ฉุกเฉิน", "emergency", "sos"):
        return EMERGENCY_INFO

    # เช็คคำยาวก่อนเสมอ ป้องกัน "อาคาร 1" ชนกับ "อาคาร 12"
    for keyword in SORTED_KEYWORDS:
        if keyword in text:
            return _FLAT_KEYWORDS[keyword]

    # ไม่เจอคำตอบที่ตรง -> ตอบ fallback
    return (
        "ขอโทษครับ ยังไม่เข้าใจคำถามนี้ 🙏\n"
        "ลองพิมพ์ 'เมนู' เพื่อดูหมวดคำถามที่ถามได้ทั้งหมด\n\n"
        + EMERGENCY_INFO
    )


